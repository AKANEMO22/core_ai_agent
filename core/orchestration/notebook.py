"""Interview notebook: the orchestrator's working memory, rendered as markdown.

Sections 1-4 and 7 are generated by code from structured state, so they cannot drift or be
rewritten by a model. Sections 5-6 come from `update_notes` (paraphrased, capped, quote-checked).
Candidate speech only appears in section 7, inside fenced `candidate_quote` blocks.
"""

import os
from typing import Any, Dict, List, Optional

from core.orchestration.coverage import CriterionCoverage
from core.runtime.tools.notes import NotesStore
from core.workspace.session import SessionWorkspace

NOTEBOOK_PATH = "context/interview_notebook.md"
NOTEBOOK_PREV_PATH = "context/interview_notebook.prev.md"


def _fence(text: str) -> str:
    safe = text.replace("```", "'''")
    return f"```candidate_quote\n{safe}\n```"


class NotebookRenderer:
    """Deterministically renders the notebook from session state, coverage and notes."""

    def render(
        self,
        session: Dict[str, Any],
        stages: List[Dict[str, Any]],
        stage_turns: Dict[str, int],
        coverage: Dict[str, CriterionCoverage],
        min_confidence: float,
        asked: List[Dict[str, Any]],
        pending_follow_ups: List[str],
        notes: Dict[str, str],
        flags: Optional[Dict[str, Any]] = None,
    ) -> str:
        lines: List[str] = ["# Interview notebook", ""]

        lines += ["## 1. Session", ""]
        for key in ("role", "level", "status", "current_stage_id", "current_turn"):
            if session.get(key) is not None:
                lines.append(f"- {key.replace('_', ' ')}: {session[key]}")
        if flags:
            active = [name for name, value in flags.items() if value]
            if active:
                lines.append(f"- flags: {', '.join(sorted(active))}")
        lines.append("")

        lines += ["## 2. Plan progress", "", "| Stage | Type | Turns used / target | Criteria |", "| --- | --- | --- | --- |"]
        for stage in stages:
            sid = stage.get("stage_id", "")
            target = stage.get("target_turns") or stage.get("turns") or "-"
            marker = " (current)" if sid == session.get("current_stage_id") else ""
            lines.append(
                f"| {sid}{marker} | {stage.get('stage_type', '-')} | {stage_turns.get(sid, 0)} / {target} | "
                f"{', '.join(stage.get('criteria', []) or []) or '-'} |"
            )
        lines.append("")

        lines += [
            "## 3. Coverage",
            "",
            f"Covered means summed confidence >= {min_confidence}.",
            "",
            "| Criterion | Weight | Must-have | Evidence | Level (1-4) | Confidence | Covered |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for cid, item in coverage.items():
            level = "-" if item.level is None else f"{item.level:.2f}"
            lines.append(
                f"| {cid} | {item.weight:.2f} | {'yes' if item.must_have else 'no'} | {len(item.evidence)} | "
                f"{level} | {item.confidence:.2f} | {'yes' if item.covered(min_confidence) else 'NO'} |"
            )
        lines.append("")

        lines += ["## 4. Questions asked and pending follow-ups", ""]
        if asked:
            for item in asked:
                lines.append(
                    f"- turn {item.get('turn')}: [{item.get('target_criterion') or '-'}] {item.get('question_id') or 'ad hoc'}"
                    f" ({item.get('directive_source') or 'n/a'})"
                )
        else:
            lines.append("- none yet")
        if pending_follow_ups:
            lines.append("")
            lines.append("Pending follow-ups:")
            lines += [f"- {text}" for text in pending_follow_ups[:5]]
        lines.append("")

        lines += ["## 5. Observations", "", notes.get("observations") or "_none_", ""]
        lines += ["## 6. Open threads", "", notes.get("open_threads") or "_none_", ""]

        lines += ["## 7. Evidence log", ""]
        any_evidence = False
        for cid, item in coverage.items():
            for evidence in item.evidence:
                any_evidence = True
                lines.append(f"- {evidence.turn_id} · {cid} · level {evidence.level} · confidence {evidence.confidence:.2f}")
                for quote in evidence.quotes[:2]:
                    lines.append(_fence(quote[:300]))
        if not any_evidence:
            lines.append("- no evaluated evidence yet")
        lines.append("")
        return "\n".join(lines)

    def write(self, workspace: SessionWorkspace, markdown: str) -> None:
        """Write atomically, keeping the previous version for audit."""
        if workspace.exists(NOTEBOOK_PATH):
            try:
                workspace.write_text(NOTEBOOK_PREV_PATH, workspace.read_text(NOTEBOOK_PATH))
            except OSError:
                pass
        workspace.write_text(NOTEBOOK_PATH, markdown)


def load_notes(workspace: SessionWorkspace) -> Dict[str, str]:
    """Current LLM-editable note sections."""
    return dict(NotesStore(workspace).load().get("sections", {}))


def asked_questions(workspace: SessionWorkspace) -> List[Dict[str, Any]]:
    """Interviewer turns with their directive provenance, in order."""
    items: List[Dict[str, Any]] = []
    for path in sorted(workspace.list_artifacts("turns"), key=lambda p: p.name):
        if not path.name.endswith("_interviewer.json"):
            continue
        rel = path.relative_to(workspace.root_path).as_posix()
        data = workspace.read_json(rel)
        items.append(
            {
                "turn": data.get("turn_number"),
                "question_id": data.get("question_id"),
                "target_criterion": data.get("target_criterion"),
                "directive_source": data.get("directive_source"),
            }
        )
    return sorted(items, key=lambda i: i.get("turn") if isinstance(i.get("turn"), int) else 0)
